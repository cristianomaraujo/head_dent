"8. EUROPEAN GUIDELINE — ESE"
"============================================================"
"The rules in this block may only be used when the clinician selects ESE or COMPARE."
"ESE RULE FOR NECROSIS AFTER LUXATION:"
"- an isolated negative pulp sensibility test does not confirm necrosis;"
"- the presence of two of the following three signs — discoloration, negative pulp sensibility test, and progressive increase in periapical radiolucency — justifies endodontic treatment;"
"- sinus tract, swelling, abscess, persistent mobility, and, in immature teeth, interruption of root development also suggest necrosis/infection."
"ESE — 1 CONCUSSION:"
"- generally does not require immediate treatment;"
"- soft diet for 1 week and adequate oral hygiene;"
"- endodontic treatment is not indicated without necrosis;"
"- an isolated negative sensibility response does not indicate root canal treatment;"
"- necrosis + closed apex → ESE-PROTOCOL A;"
"- necrosis + open apex → ESE-PROTOCOL B;"
"- follow-up: 4 weeks and 1 year."
"ESE — 2 SUBLUXATION:"
"- clean with water, saline, or chlorhexidine;"
"- suture lacerations when present;"
"- a flexible splint may be used for up to 2 weeks for stabilization/comfort;"
"- do not indicate endodontic treatment without necrosis;"
"- closed-apex necrosis → ESE-A;"
"- open-apex necrosis → ESE-B;"
"- follow-up: 2 weeks, 12 weeks, 6 months, and 1 year;"
"- remove the splint at 2 weeks when used."
"ESE — 3 EXTRUSION:"
"- anesthesia;"
"- clean the exposed root surface with saline;"
"- if still displaced, reposition with axial digital pressure;"
"- if already adequately repositioned, do not repeat;"
"- flexible splint for 2 weeks;"
"- marginal fracture may require additional stabilization;"
"- in immature teeth, prioritize preservation/revascularization;"
"- an isolated initial negative sensibility test does not indicate root canal treatment;"
"- closed-apex necrosis → ESE-A;"
"- open-apex necrosis → ESE-B;"
"- follow-up: 2 wk, 4 wk, 8 wk, 12 wk, 6 mo, 1 yr, and annually for ≥5 years."
"ESE — 4 LATERAL LUXATION:"
"- anesthesia;"
"- if still displaced, reposition digitally or with forceps while releasing the bony lock;"
"- if already adequately repositioned, do not repeat;"
"- flexible splint for 4 weeks;"
"- open apex: prioritize preservation/revascularization;"
"- necrosis + inflammatory resorption → ESE-E;"
"- closed apex with severe displacement: high risk; endodontic treatment is favored → ESE-A;"
"- follow-up: 2 wk, 4 wk, 8 wk, 12 wk, 6 mo, 1 yr, and annually for 5 years."
"ESE — 5 INTRUSION:"
"- open apex: allow spontaneous re-eruption;"
"- if no re-eruption occurs within 4 weeks: orthodontic repositioning;"
"- do not initiate immediate endodontic treatment when revascularization is possible;"
"- open apex + necrosis → ESE-B;"
